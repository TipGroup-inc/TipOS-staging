#include <stdint.h>

#define VGA_GFX_SEGMENT 0xA0000
#define VGA_GFX_WIDTH  320
#define VGA_GFX_HEIGHT 200

static inline void outb(uint16_t port, uint8_t val) {
    __asm__ volatile ("outb %0, %1" :: "a"(val), "Nd"(port));
}
static inline uint8_t inb(uint16_t port) {
    uint8_t ret;
    __asm__ volatile ("inb %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

/* Desabilita proteção do CRTC antes de programar */
static void crtc_write(uint8_t idx, uint8_t val) {
    outb(0x3D4, idx);
    outb(0x3D5, val);
}

void vga_gfx_init(void) {
    outb(0x3C2, 0x63);

    outb(0x3C4, 0x00); outb(0x3C5, 0x03);
    outb(0x3C4, 0x01); outb(0x3C5, 0x01);
    outb(0x3C4, 0x02); outb(0x3C5, 0x0F);
    outb(0x3C4, 0x03); outb(0x3C5, 0x00);
    outb(0x3C4, 0x04); outb(0x3C5, 0x0E);

    crtc_write(0x11, inb(0x3D5) & ~0x80);
    crtc_write(0x00, 0x5F); crtc_write(0x01, 0x4F);
    crtc_write(0x02, 0x50); crtc_write(0x03, 0x82);
    crtc_write(0x04, 0x54); crtc_write(0x05, 0x80);
    crtc_write(0x06, 0x0B); crtc_write(0x07, 0x3E);
    crtc_write(0x08, 0x00); crtc_write(0x09, 0x41);
    crtc_write(0x10, 0xEA); crtc_write(0x11, 0xAC);
    crtc_write(0x12, 0xDF); crtc_write(0x13, 0x28);
    crtc_write(0x14, 0x00); crtc_write(0x15, 0xE7);
    crtc_write(0x16, 0x06); crtc_write(0x17, 0xE3);

    outb(0x3CE, 0x00); outb(0x3CF, 0x00);
    outb(0x3CE, 0x01); outb(0x3CF, 0x00);
    outb(0x3CE, 0x02); outb(0x3CF, 0x00);
    outb(0x3CE, 0x03); outb(0x3CF, 0x00);
    outb(0x3CE, 0x04); outb(0x3CF, 0x00);
    outb(0x3CE, 0x05); outb(0x3CF, 0x40);
    outb(0x3CE, 0x06); outb(0x3CF, 0x05);
    outb(0x3CE, 0x07); outb(0x3CF, 0x0F);
    outb(0x3CE, 0x08); outb(0x3CF, 0xFF);

    outb(0x3C0, 0x00 | 0x20);
    for (int i = 0; i < 16; i++) {
        outb(0x3C0, i);
        outb(0x3C0, (i << 2) & 0x3F);
    }
    outb(0x3C0, 0x20);

    outb(0x3C8, 0x00);
    for (int i = 0; i < 256; i++) {
        outb(0x3C9, i >> 2);
        outb(0x3C9, i >> 2);
        outb(0x3C9, i >> 2);
    }
}

void vga_gfx_putpixel(int x, int y, uint8_t color) {
    if (x < 0 || x >= VGA_GFX_WIDTH || y < 0 || y >= VGA_GFX_HEIGHT) return;
    uint8_t *fb = (uint8_t *)VGA_GFX_SEGMENT;
    fb[y * VGA_GFX_WIDTH + x] = color;
}

void vga_gfx_fillrect(int x, int y, int w, int h, uint8_t color) {
    uint8_t *fb = (uint8_t *)VGA_GFX_SEGMENT;
    for (int row = 0; row < h && y + row < VGA_GFX_HEIGHT; row++)
        for (int col = 0; col < w && x + col < VGA_GFX_WIDTH; col++)
            fb[(y + row) * VGA_GFX_WIDTH + (x + col)] = color;
}

void vga_gfx_clear(uint8_t color) {
    vga_gfx_fillrect(0, 0, VGA_GFX_WIDTH, VGA_GFX_HEIGHT, color);
}

void vga_gfx_restore_text(void) {
    outb(0x3C2, 0x67);
    outb(0x3C4, 0x00); outb(0x3C5, 0x03);
    outb(0x3C4, 0x01); outb(0x3C5, 0x01);
    outb(0x3C4, 0x02); outb(0x3C5, 0x03);
    outb(0x3C4, 0x04); outb(0x3C5, 0x03);

    crtc_write(0x11, inb(0x3D5) & ~0x80);
    crtc_write(0x00, 0x5F); crtc_write(0x01, 0x4F);
    crtc_write(0x02, 0x50); crtc_write(0x03, 0x82);
    crtc_write(0x04, 0x55); crtc_write(0x05, 0x81);
    crtc_write(0x06, 0xBF); crtc_write(0x07, 0x1F);
    crtc_write(0x08, 0x00); crtc_write(0x09, 0x4F);
    crtc_write(0x10, 0x9C); crtc_write(0x11, 0x8E);
    crtc_write(0x12, 0x8F); crtc_write(0x13, 0x28);
    crtc_write(0x14, 0x00); crtc_write(0x15, 0x96);
    crtc_write(0x16, 0xB9); crtc_write(0x17, 0xA3);

    outb(0x3CE, 0x00); outb(0x3CF, 0x00);
    outb(0x3CE, 0x01); outb(0x3CF, 0x00);
    outb(0x3CE, 0x02); outb(0x3CF, 0x00);
    outb(0x3CE, 0x03); outb(0x3CF, 0x00);
    outb(0x3CE, 0x04); outb(0x3CF, 0x00);
    outb(0x3CE, 0x05); outb(0x3CF, 0x40);
    outb(0x3CE, 0x06); outb(0x3CF, 0x0E);
    outb(0x3CE, 0x07); outb(0x3CF, 0x0F);
    outb(0x3CE, 0x08); outb(0x3CF, 0xFF);

    outb(0x3C0, 0x00 | 0x20);
    for (int i = 0; i < 16; i++) {
        outb(0x3C0, i);
        outb(0x3C0, (i << 2) & 0x3F);
    }
    outb(0x3C0, 0x20);
}
