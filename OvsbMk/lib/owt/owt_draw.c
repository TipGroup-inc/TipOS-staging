/* ~~ owt_draw_pixel ~~ */
/* ~ simples mas essencial, n mexe sem saber oq ta fazendo */
void owt_draw_pixel(int x, int y, uint32_t color) {
    uint32_t *bb = wm_get_backbuf();
    if (!bb) return;
    uint32_t st = wm_get_stride();
    int sw = wm_get_scr_w(), sh = wm_get_scr_h();
    if (x < 0 || y < 0 || x >= sw || y >= sh) return;
    bb[y * st + x] = color;
}

/* ~~ owt_draw_rect ~~ */
/* ~ cuidado que essa aqui morde ~ */
void owt_draw_rect(int x, int y, int w, int h, uint32_t color) {
    for (int py = y; py < y + h; py++)
        for (int px = x; px < x + w; px++)
            owt_draw_pixel(px, py, color);
}

/* ~~ owt_draw_char ~~ */
/* ~ essa demorou pra debugar, respeita ~ */
void owt_draw_char(int x, int y, char c, uint32_t color) {
    if (c < 32 || c > 126) return;
    const uint8_t *g = font[(unsigned char)c - 32];
    for (int r = 0; r < 8; r++) {
        uint8_t bits = g[r];
        for (int cl = 0; cl < 8; cl++) {
            if (bits & (1 << cl)) {
                owt_draw_pixel(x + cl, y + r * 2, color);
                owt_draw_pixel(x + cl, y + r * 2 + 1, color);
            }
        }
    }
}

/* ~~ owt_draw_text ~~ */
/* ~ essa funcao aqui e a mais importante, presta atencao baka! */
void owt_draw_text(int x, int y, const char *text, uint32_t color) {
    int cx = x;
    while (*text) { owt_draw_char(cx, y, *text, color); cx += 8; text++; }
}



