/* glyph atlas — pre-computed 32-bit pixel masks (0xFFFFFFFF = font on, 0 = off) */
static uint32_t glyph_atlas[95][16][8];

static void vesa_build_atlas(void) {
    for (int i = 0; i < 95; i++) {
        for (int r = 0; r < 8; r++) {
            uint8_t bits = font8x8[i][r];
            for (int c = 0; c < 8; c++) {
                uint32_t v = (bits & (1 << c)) ? 0xFFFFFFFF : 0x00000000;
                glyph_atlas[i][r*2][c] = v;
                glyph_atlas[i][r*2+1][c] = v;
            }
        }
    }
}

int vesa_init(framebuffer_t *fb) {
    g_fb = fb;
    vesa_build_atlas();

    uint64_t pml4 = pml4_get_current();
    size_t fb_size = fb->pitch * fb->height;
    fb_size = (fb_size + 0x1FFFFF) & ~0x1FFFFF;

    return pml4_map_phys(pml4, fb->addr, fb->addr, fb_size, 1);
}

void vesa_flush(void) {
    if (!g_fb || !g_backbuffer) return;
    uint32_t *fb = (uint32_t *)(uintptr_t)g_fb->addr;
    size_t pixels = (size_t)g_fb->pitch * g_fb->height / 4;
    size_t i = 0;
#if defined(__x86_64__)
    for (; i + 1 < pixels; i += 2)
        *(volatile uint64_t *)&fb[i] = *(uint64_t *)&g_backbuffer[i];
#endif
    for (; i < pixels; i++) fb[i] = g_backbuffer[i];
}

void vesa_draw_pixel(int x, int y, uint32_t color) {
    if (!g_fb) return;
    if (x < 0 || y < 0 || (uint32_t)x >= g_fb->width || (uint32_t)y >= g_fb->height)
        return;

    uint32_t *buf = fb_target();
    uint32_t stride = g_fb->pitch / 4;
    buf[y * stride + x] = color;
}

void vesa_fill_screen(uint32_t color) {
    if (!g_fb) return;

    uint32_t *buf = fb_target();
    uint32_t stride = g_fb->pitch / 4;

    for (uint32_t y = 0; y < g_fb->height; y++) {
        uint32_t *row = &buf[y * stride];
        for (uint32_t x = 0; x < g_fb->width; x += 8) {
            row[x] = color; row[x+1] = color; row[x+2] = color; row[x+3] = color;
            row[x+4] = color; row[x+5] = color; row[x+6] = color; row[x+7] = color;
        }
    }
}

void vesa_draw_rect(int x, int y, int w, int h, uint32_t color) {
    if (!g_fb) return;
    if (w <= 0 || h <= 0) return;

    uint32_t *buf = fb_target();
    uint32_t stride = g_fb->pitch / 4;

    int x0 = x < 0 ? 0 : x;
    int y0 = y < 0 ? 0 : y;
    int x1 = x + w;
    int y1 = y + h;

    if (x1 > (int)g_fb->width)  x1 = g_fb->width;
    if (y1 > (int)g_fb->height) y1 = g_fb->height;

    for (int py = y0; py < y1; py++) {
        for (int px = x0; px < x1; px++) {
            buf[py * stride + px] = color;
        }
    }
}

void vesa_draw_char(int x, int y, char c, uint32_t color) {
    if (!g_fb) return;
    if (c < 32 || c > 126) return;

    const uint8_t *glyph = font8x8[(unsigned char)c - 32];

    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (1 << col)) {
                int px = x + col;
                int py = y + row * 2;
                vesa_draw_pixel(px, py, color);
                vesa_draw_pixel(px, py + 1, color);
            }
        }
    }
}

void vesa_draw_cell(int x, int y, char c, uint32_t fg, uint32_t bg) {
    if (!g_fb) return;
    uint32_t stride = g_fb->pitch / 4;
    int ci = (unsigned char)c - 32;
    if (ci < 0 || ci >= 95) ci = 0;

    uint32_t *dst_fb = (uint32_t *)(uintptr_t)g_fb->addr;

    for (int r = 0; r < 16; r++) {
        uint32_t *mask = glyph_atlas[ci][r];

        uint32_t p0 = (mask[0] & fg) | (~mask[0] & bg);
        uint32_t p1 = (mask[1] & fg) | (~mask[1] & bg);
        uint32_t p2 = (mask[2] & fg) | (~mask[2] & bg);
        uint32_t p3 = (mask[3] & fg) | (~mask[3] & bg);
        uint32_t p4 = (mask[4] & fg) | (~mask[4] & bg);
        uint32_t p5 = (mask[5] & fg) | (~mask[5] & bg);
        uint32_t p6 = (mask[6] & fg) | (~mask[6] & bg);
        uint32_t p7 = (mask[7] & fg) | (~mask[7] & bg);

        if (g_backbuffer) {
            uint32_t *db = &g_backbuffer[(y + r) * stride + x];
            db[0]=p0; db[1]=p1; db[2]=p2; db[3]=p3;
            db[4]=p4; db[5]=p5; db[6]=p6; db[7]=p7;
        }
        uint32_t *df = &dst_fb[(y + r) * stride + x];
        df[0]=p0; df[1]=p1; df[2]=p2; df[3]=p3;
        df[4]=p4; df[5]=p5; df[6]=p6; df[7]=p7;
    }
}

void vesa_scroll(int pixel_rows) {
    if (!g_fb || !g_backbuffer) return;
    uint32_t *buf = g_backbuffer;
    uint32_t stride = g_fb->pitch / 4;
    uint32_t h = g_fb->height;
    uint32_t w = stride;
    size_t shift_offset = (size_t)pixel_rows * w;
    size_t total_copy = (size_t)(h - pixel_rows) * w;
    for (size_t i = 0; i < total_copy; i++)
        buf[i] = buf[i + shift_offset];
    size_t clear_start = total_copy;
    size_t clear_end = (size_t)h * w;
    for (size_t i = clear_start; i < clear_end; i++)
        buf[i] = 0;
}

void vesa_draw_text(int x, int y, const char *text, uint32_t color) {
    int cx = x;
    int cy = y;

    while (*text) {
        char c = *text;

        if (c == '\n') {
            cx = x;
            cy += 16;
        } else {
            vesa_draw_char(cx, cy, c, color);
            cx += 8;
        }

        text++;
    }
}
